#!/usr/bin/env python3
"""Re-run the deterministic paths and confirm they rebuild byte-identically.

Part B (pure recomputation from the two artifacts) and Part A1 (seeded, multiprocessed)
are re-run from scratch and hashed.  `wall_seconds` is excluded from the hash because it
is a timing, not a result.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import time
from pathlib import Path

from loguru import logger

HERE = Path(__file__).resolve().parent
PY = str(HERE / ".venv" / "bin" / "python")


C1_ADDENDUM_MARKER = "## Part C1 addendum -- the simulated null behind row C18"


def content_hash(p: Path) -> str:
    if p.name == "patch_table.md":
        # eval.py appends a Part-C1 addendum to the table partB.py writes; the addendum
        # is regenerated by eval.py, not by partB.py, so the determinism check compares
        # the partB-generated part only (the addendum's own idempotence is checked by
        # running eval.py twice, see below).
        return hashlib.sha256(
            p.read_text().split(C1_ADDENDUM_MARKER)[0].rstrip().encode()).hexdigest()
    if p.suffix == ".json":
        d = json.loads(p.read_text())
        if isinstance(d, dict):
            d.pop("wall_seconds", None)
        return hashlib.sha256(json.dumps(d, sort_keys=True, default=str).encode()).hexdigest()
    return hashlib.sha256(p.read_bytes()).hexdigest()


TARGETS = {
    "stage_b.json": HERE / "results" / "stage_b.json",
    "claims_ledger.csv": HERE / "claims_ledger.csv",
    "patch_table.md": HERE / "patch_table.md",
    "stage_a1.json": HERE / "results" / "stage_a1.json",
    "stage_c2.json": HERE / "results" / "stage_c2.json",
}
COMMANDS = [[PY, "partB.py"], [PY, "partA.py", "--stage", "a1"],
            [PY, "partC.py", "--stage", "c2"]]


def main() -> None:
    before = {k: content_hash(p) for k, p in TARGETS.items() if p.exists()}
    t0 = time.perf_counter()
    for cmd in COMMANDS:
        r = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True)
        if r.returncode != 0:
            logger.error(f"{cmd} failed: {r.stderr[-800:]}")
            raise SystemExit(1)
    after = {k: content_hash(p) for k, p in TARGETS.items() if p.exists()}
    rows = []
    for k in sorted(before):
        rows.append({"file": k, "hash_run_1": before[k], "hash_run_2": after.get(k),
                     "identical": before[k] == after.get(k)})
        logger.info(f"{k:22} {'IDENTICAL' if rows[-1]['identical'] else 'DIFFERS'} "
                    f"{before[k][:16]}")
    # C1 spot-replicate: re-run three nominal-sweep cells with the same seed and confirm
    # the co-inclusion p-values reproduce EXACTLY.  Re-running all 48 cells plus the four
    # calibrated null bands would cost ~13 minutes; three cells cost seconds and test the
    # same code path (sampler -> PairAccumulator -> chi-square).
    c1_rows = []
    c1_path = HERE / "results" / "stage_c1.json"
    if c1_path.exists():
        sys.path.insert(0, str(HERE))
        import partC as C  # noqa: PLC0415
        stored = {(r["n"], r["k"]): r for r in json.loads(c1_path.read_text())["nominal_sweep"]}
        c1_json = json.loads(c1_path.read_text())
        for cell in [(1000, 10), (500, 50), (2000, 100)]:
            rep = C.c1_nominal_sweep(T=c1_json["T"], grid=[cell], seed=c1_json["seed"])[0]
            st = stored[cell]
            c1_rows.append({
                "cell": list(cell),
                "coinc_p_stored": st["coinc_p_nominal"],
                "coinc_p_replicate": rep["coinc_p_nominal"],
                "coinc_chi2_stored": st["coinc_chi2"],
                "coinc_chi2_replicate": rep["coinc_chi2"],
                "identical": (st["coinc_p_nominal"] == rep["coinc_p_nominal"]
                              and st["coinc_chi2"] == rep["coinc_chi2"]),
            })
            logger.info(f"c1 replicate {cell}: "
                        f"{'IDENTICAL' if c1_rows[-1]['identical'] else 'DIFFERS'}")

    out = {"rows": rows,
           "c1_nominal_spot_replicate": c1_rows,
           "c1_spot_replicate_all_identical": (all(r["identical"] for r in c1_rows)
                                               if c1_rows else None),
           "all_identical": (all(r["identical"] for r in rows)
                             and all(r["identical"] for r in c1_rows)),
           "commands_rerun": [" ".join(c[1:]) for c in COMMANDS],
           "hash_excludes": ["wall_seconds"],
           "wall_seconds": time.perf_counter() - t0}
    (HERE / "results" / "stage_determinism.json").write_text(json.dumps(out, indent=1))
    logger.info(f"all_identical = {out['all_identical']}")


if __name__ == "__main__":
    logger.remove()
    logger.add(sys.stdout, level="INFO", format="{time:HH:mm:ss}|{level:<7}|{message}")
    main()
