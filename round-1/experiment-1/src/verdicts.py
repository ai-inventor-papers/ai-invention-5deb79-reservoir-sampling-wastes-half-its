#!/usr/bin/env python3
"""Head-to-head: the standard Monte-Carlo uniformity test versus the exact prefix DP.

This is the controlled comparison the experiment turns on.  For one and the same
(candidate, n, k) cell, four verdicts are produced through ONE pipeline:

  BASELINE-1  ``mc_final_first_order``  -- the textbook practice and the literal user ask:
              simulate T streams, count how often each item ends in the final reservoir,
              report the max deviation from k/n, flag it against a simulated null band.
  BASELINE-2  ``mc_final_pairwise``     -- a strictly stronger Monte-Carlo test: the same
              streams, but the max standardised deviation of the C(n,2) co-inclusion
              frequencies.
  BASELINE-3  ``mc_all_prefix``         -- the strongest Monte-Carlo test we can build:
              the ANYTIME statistic, max over every prefix i of the standardised
              first-order deviation, with the null band generated by the classical
              sampler itself (whose anytime uniformity is certified exactly by gate G1).
  OURS        ``exact_dp``              -- the exact-rational prefix DP; a zero here is a
              proof, not an estimate.

Ground truth is the exact DP verdict, which is a theorem about the cell, so the table is
a genuine confusion matrix for the three Monte-Carlo tests.
"""

from __future__ import annotations

import time
from fractions import Fraction
from typing import Any, Callable

import numpy as np
from loguru import logger

import candidates
import fibermap
import montecarlo as mc
from exact_dp import run_exact_dp

def mc_pvalue(observed: float, null_values: list[float]) -> float:
    """Exact Monte-Carlo p-value: (1 + #{null >= observed}) / (R + 1).

    Valid for any R and free of percentile-estimation bias, unlike thresholding on an
    empirical p95 estimated from a handful of replicates.
    """
    R = len(null_values)
    ge = sum(1 for v in null_values if v >= observed)
    return (1.0 + ge) / (R + 1.0)


def mc_flag(observed: float, null_values: list[float], alpha: float = 0.01) -> tuple[bool, float]:
    p = mc_pvalue(observed, null_values)
    return (p <= alpha, p)


UNIFORM = "UNIFORM"
NOT_UNIFORM = "NOT_UNIFORM"
UNDECIDABLE = "INFEASIBLE_AT_THIS_SCALE"

# Which candidates the Monte-Carlo harness can actually simulate, and how.
MC_SPEC: dict[str, dict[str, Any]] = {
    "S0": {"sampler": "algo_l", "rule": "uniform"},
    "S1n": {"sampler": "algo_l", "rule": "summodk"},
    "C-NOACCEPT": {"sampler": "algo_l", "rule": "largest"},
    "S5-CIRC": {"sampler": "circwindow", "rule": "-"},
    "S1": {"sampler": "algo_l", "rule": "table:repair"},
    "S1f": {"sampler": "algo_l", "rule": "table:flow"},
}


# --------------------------------------------------------------------------------------
# Table-driven eviction for the Monte Carlo harness
# --------------------------------------------------------------------------------------


def make_table_rule(which: str, k: int) -> Callable:
    """Eviction rule that reads the exact transportation-flow tables (samplers S1 / S1f).

    Only usable where the tables exist, i.e. where C(i,k) is enumerable -- which is
    exactly the regime where the exact DP also runs.  That is the point of the matched
    panel: both instruments see the same cells.
    """

    def rule(res: np.ndarray, arriving: np.ndarray, kk: int, rng: np.random.Generator) -> np.ndarray:
        out = np.empty(len(res), dtype=np.int64)
        for j in np.unique(arriving):
            m = arriving == j
            tbl = fibermap.eviction_table(which, int(j) - 1, kk)
            sub = res[m]
            u = rng.random(int(m.sum()))
            pos = np.empty(len(sub), dtype=np.int64)
            for r_i, (row, uu) in enumerate(zip(sub, u)):
                entries = tbl[tuple(int(x) for x in row)]
                acc = 0.0
                chosen = entries[-1][0]
                for p_idx, prob in entries:
                    acc += float(prob)
                    if uu < acc:
                        chosen = p_idx
                        break
                pos[r_i] = chosen
            out[m] = pos
        return out

    return rule


def resolve_rule(key: str, k: int) -> tuple[str, Callable | None]:
    spec = MC_SPEC[key]
    if spec["sampler"] == "circwindow":
        return "circwindow", None
    r = spec["rule"]
    if r.startswith("table:"):
        return "algo_l", make_table_rule(r.split(":", 1)[1], k)
    return "algo_l", {"uniform": mc.rule_uniform, "summodk": mc.rule_summodk, "largest": mc.rule_largest}[r]


# --------------------------------------------------------------------------------------
# The anytime (all-prefix) Monte-Carlo statistic
# --------------------------------------------------------------------------------------


def simulate_prefix_counts(
    key: str, n: int, k: int, T: int, rng: np.random.Generator, *, chunk: int = 50_000
) -> np.ndarray:
    """Per-item simulation that snapshots the reservoir at EVERY prefix.

    Returns counts of shape (n+1, n+1): ``counts[i, x]`` = number of streams whose
    reservoir after i items contains item x.  Only counts are kept, never the reservoirs.
    """
    counts = np.zeros((n + 1, n + 1), dtype=np.int64)
    sampler, rule = resolve_rule(key, k)
    done = 0
    while done < T:
        M = min(chunk, T - done)
        if sampler == "circwindow":
            anchor = np.ones(M, dtype=np.int64)
            for i in range(1, n + 1):
                if i >= 2:
                    anchor = np.where(rng.random(M) < 1.0 / i, i, anchor)
                if i >= k:
                    t = np.arange(k, dtype=np.int64)
                    win = ((anchor[:, None] - 1 + t[None, :]) % i) + 1
                    counts[i] += np.bincount(win.ravel(), minlength=n + 1)
        else:
            res = np.tile(np.arange(1, k + 1, dtype=np.int64), (M, 1))
            counts[k] += np.bincount(res.ravel(), minlength=n + 1)
            for i in range(k + 1, n + 1):
                accept = rng.random(M) < (k / i)
                if accept.any():
                    sel = np.nonzero(accept)[0]
                    res_a = res[sel]
                    arriving = np.full(len(sel), i, dtype=np.int64)
                    r = np.asarray(rule(res_a, arriving, k, rng), dtype=np.int64)
                    res[sel] = mc._evict_insert(res_a, arriving, r, k)
                counts[i] += np.bincount(res.ravel(), minlength=n + 1)
        done += M
    return counts


def all_prefix_statistic(counts: np.ndarray, n: int, k: int, T: int) -> dict[str, Any]:
    """max over prefixes i of the standardised max first-order deviation."""
    best_z, best_i, best_x, best_dev = -1.0, None, None, 0.0
    for i in range(k, n + 1):
        p = k / i
        sd = np.sqrt(p * (1 - p) / T)
        freq = counts[i, 1 : i + 1] / T
        dev = np.abs(freq - p)
        j = int(np.argmax(dev))
        z = float(dev[j] / sd) if sd > 0 else 0.0
        if z > best_z:
            best_z, best_i, best_x, best_dev = z, i, j + 1, float(dev[j])
    return {"max_z": best_z, "argmax_prefix": best_i, "argmax_item": best_x, "max_dev": best_dev}


def all_prefix_null_band(n: int, k: int, T: int, R: int, seed: int) -> dict[str, Any]:
    """Null band for the anytime statistic, generated by the classical sampler itself.

    S0's anytime uniformity is not assumed -- it is certified exactly by gate G1, so
    using it as the null generator is legitimate and captures the true prefix-to-prefix
    dependence that an i.i.d.-per-prefix null would miss.
    """
    vals: list[float] = []
    for r in range(R):
        rng = np.random.Generator(np.random.PCG64(seed * 1000 + r))
        c = simulate_prefix_counts("S0", n, k, T, rng)
        vals.append(all_prefix_statistic(c, n, k, T)["max_z"])
    a = np.asarray(vals)
    return {
        "R": R,
        "T": T,
        "generator": "S0_CLASSICAL_R (anytime uniformity certified exactly by gate G1)",
        "mean": float(a.mean()),
        "p50": float(np.percentile(a, 50)),
        "p95": float(np.percentile(a, 95)),
        "p99": float(np.percentile(a, 99)),
        "max": float(a.max()),
        "values": [float(v) for v in a],
    }


# --------------------------------------------------------------------------------------
# One matched cell
# --------------------------------------------------------------------------------------


def run_matched_cell(
    key: str,
    n: int,
    k: int,
    T: int,
    seed: int,
    *,
    final_null: dict[str, Any],
    prefix_null: dict[str, Any],
) -> dict[str, Any]:
    """Exact DP ground truth + three Monte-Carlo verdicts, on identical settings."""
    t0 = time.perf_counter()
    rep = run_exact_dp(candidates.build(key, n=n, k=k), n, k)
    dp_seconds = time.perf_counter() - t0
    truth = UNIFORM if rep.i_first_fail is None else NOT_UNIFORM

    t1 = time.perf_counter()
    rng = np.random.Generator(np.random.PCG64(seed))
    sampler, rule = resolve_rule(key, k)
    if sampler == "circwindow":
        reservoirs = mc.simulate_circwindow_stepwise(n, k, T, rng)
    else:
        reservoirs = mc.simulate_algo_l(n, k, T, rule, rng)
    fo = mc.first_order_stats(reservoirs, n, k)
    pr = mc.pair_stats(reservoirs, n, k)
    del reservoirs

    counts = simulate_prefix_counts(key, n, k, T, np.random.Generator(np.random.PCG64(seed + 77)))
    ap = all_prefix_statistic(counts, n, k, T)
    del counts
    mc_seconds = time.perf_counter() - t1

    f_fo, p_fo = mc_flag(fo["max_dev"], final_null["first_order"]["values"])
    f_pr, p_pr = mc_flag(pr["max_abs_z"], final_null["pair_z"]["values"])
    f_ap, p_ap = mc_flag(ap["max_z"], prefix_null["values"])
    v_fo = NOT_UNIFORM if f_fo else UNIFORM
    v_pr = NOT_UNIFORM if f_pr else UNIFORM
    v_ap = NOT_UNIFORM if f_ap else UNIFORM

    return {
        "candidate": key,
        "candidate_description": candidates.DESCRIPTIONS[key],
        "n": n,
        "k": k,
        "T": T,
        "seed": seed,
        "truth_exact_dp": truth,
        "exact_dp": {
            "verdict": truth,
            "i_first_fail": rep.i_first_fail,
            "m1_rel_at_failure": float(rep.m1_rel_at_failure) if rep.m1_rel_at_failure else 0.0,
            "n_prefixes_proved_uniform": sum(1 for r in rep.rows if r.m1_abs == 0),
            "n_prefixes": len(rep.rows),
            "max_states": rep.max_states_seen,
            "seconds": dp_seconds,
            "forward_passes_over_the_stream": 0,
            "random_bits_consumed": 0,
        },
        "mc_final_first_order": {
            "mc_p_value": p_fo,
            "flag_rule": "exact Monte-Carlo p-value (1 + #(null >= obs))/(R+1) <= 0.01",
            "verdict": v_fo,
            "max_dev": fo["max_dev"],
            "argmax_item": fo["argmax_item"],
            "null_p95": final_null["first_order"]["p95"],
            "in_band_units": fo["max_dev"] / final_null["first_order"]["p95"],
            "chi2": fo["chi2"],
        },
        "mc_final_pairwise": {
            "mc_p_value": p_pr,
            "flag_rule": "exact Monte-Carlo p-value (1 + #(null >= obs))/(R+1) <= 0.01",
            "verdict": v_pr,
            "max_abs_z": pr["max_abs_z"],
            "argmax_pair": pr["argmax_pair"],
            "null_p95": final_null["pair_z"]["p95"],
            "in_band_units": pr["max_abs_z"] / final_null["pair_z"]["p95"],
            "frac_zero_pairs": pr["frac_zero_pairs"],
        },
        "mc_all_prefix": {
            "mc_p_value": p_ap,
            "flag_rule": "exact Monte-Carlo p-value (1 + #(null >= obs))/(R+1) <= 0.01",
            "verdict": v_ap,
            "max_z": ap["max_z"],
            "argmax_prefix": ap["argmax_prefix"],
            "argmax_item": ap["argmax_item"],
            "null_p95": prefix_null["p95"],
            "in_band_units": ap["max_z"] / prefix_null["p95"],
        },
        "mc_seconds": mc_seconds,
        "mc_stream_passes": 2 * T,
        "agreement": {
            "mc_final_first_order": v_fo == truth,
            "mc_final_pairwise": v_pr == truth,
            "mc_all_prefix": v_ap == truth,
            "exact_dp": True,
        },
    }


def confusion(rows: list[dict[str, Any]], method: str) -> dict[str, Any]:
    """Confusion matrix of one Monte-Carlo test against the exact-DP ground truth."""
    tp = fp = tn = fn = 0
    for r in rows:
        truth = r["truth_exact_dp"]
        pred = r[method]["verdict"]
        if truth == NOT_UNIFORM and pred == NOT_UNIFORM:
            tp += 1
        elif truth == NOT_UNIFORM and pred == UNIFORM:
            fn += 1
        elif truth == UNIFORM and pred == NOT_UNIFORM:
            fp += 1
        else:
            tn += 1
    tot = tp + fp + tn + fn
    return {
        "method": method,
        "n_cells": tot,
        "true_positive": tp,
        "false_negative": fn,
        "false_positive": fp,
        "true_negative": tn,
        "accuracy": (tp + tn) / tot if tot else None,
        "recall_on_broken_samplers": tp / (tp + fn) if (tp + fn) else None,
        "specificity_on_correct_samplers": tn / (tn + fp) if (tn + fp) else None,
        "missed_cells": [
            f"{r['candidate']}@n={r['n']},k={r['k']}"
            for r in rows
            if r["truth_exact_dp"] == NOT_UNIFORM and r[method]["verdict"] == UNIFORM
        ],
    }


